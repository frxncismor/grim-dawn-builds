import { spawnSync } from 'node:child_process';
import { cpSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const apiRoot = fileURLToPath(new URL('../..', import.meta.url));
const migrationsDir = join(apiRoot, 'drizzle');
const metaDir = join(migrationsDir, 'meta');
const drizzleKitBin = join(apiRoot, 'node_modules', 'drizzle-kit', 'bin.cjs');

interface Journal {
  entries: { idx: number; tag: string }[];
}

const sqlFiles = () => readdirSync(migrationsDir).filter((f) => f.endsWith('.sql'));

const readJournal = (): Journal =>
  JSON.parse(readFileSync(join(metaDir, '_journal.json'), 'utf8')) as Journal;

describe('initial migration (0000, generated by drizzle-kit)', () => {
  it('ships exactly one SQL migration, named 0000_*', () => {
    const files = sqlFiles();
    expect(files).toHaveLength(1);
    expect(files[0]).toMatch(/^0000_[a-z0-9_]+\.sql$/);
  });

  it('registers that migration as the single journal entry', () => {
    const journal = readJournal();
    const sql = sqlFiles()[0] ?? '';
    expect(journal.entries.map((e) => e.idx)).toEqual([0]);
    expect(journal.entries[0]?.tag).toBe(sql.replace(/\.sql$/, ''));
  });

  it('contains no handwritten gates, roles, views or policies (those are T-055)', () => {
    const sql = readFileSync(join(migrationsDir, sqlFiles()[0] ?? ''), 'utf8');
    for (const forbidden of [
      /CREATE\s+TRIGGER/i,
      /CREATE\s+VIEW/i,
      /CREATE\s+ROLE/i,
      /CREATE\s+POLICY/i,
      /CREATE\s+FUNCTION/i,
      /\bGRANT\b/i,
      /\bDO\s+\$\$/i,
    ]) {
      expect(sql, String(forbidden)).not.toMatch(forbidden);
    }
  });

  it('creates the core enums and tables, including content_origin', () => {
    const sql = readFileSync(join(migrationsDir, sqlFiles()[0] ?? ''), 'utf8');
    expect(sql).toMatch(/CREATE TYPE "public"\."review_state" AS ENUM/);
    expect(sql).toMatch(/CREATE TABLE "builds"/);
    expect(sql).toMatch(/CREATE TABLE "assets"/);
    expect(sql).toMatch(/CREATE TABLE "mastery_combinations"/);
    expect(sql).toMatch(/CREATE TABLE "content_origin"/);
    expect(sql).toMatch(/CREATE TABLE "tier_entries"/);
  });
});

describe('drizzle-kit generate produces no diff after 0000', () => {
  it('reports no schema changes and writes no new migration files', () => {
    const work = mkdtempSync(join(tmpdir(), 'gd-drizzle-nodiff-'));
    try {
      const out = join(work, 'drizzle');
      cpSync(migrationsDir, out, { recursive: true });
      const before = listFiles(out);

      const configPath = join(work, 'drizzle.config.mjs');
      const schemaPath = join(apiRoot, 'src', 'db', 'schema.ts').replace(/\\/g, '/');
      writeFileSync(
        configPath,
        `export default ${JSON.stringify({
          dialect: 'postgresql',
          schema: schemaPath,
          out: './drizzle',
        })};\n`,
      );

      const run = spawnSync(process.execPath, [drizzleKitBin, 'generate', '--config', configPath], {
        cwd: work,
        encoding: 'utf8',
        env: { ...process.env, DATABASE_URL: '' },
      });
      const output = `${run.stdout}\n${run.stderr}`;

      expect(run.status, output.slice(-2000)).toBe(0);
      expect(output).toMatch(/No schema changes/i);
      expect(listFiles(out)).toEqual(before);
    } finally {
      rmSync(work, { recursive: true, force: true });
    }
  }, 120_000);
});

function listFiles(root: string): string[] {
  const out: string[] = [];
  const walk = (dir: string, prefix: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) walk(join(dir, entry.name), rel);
      else out.push(rel);
    }
  };
  walk(root, '');
  return out.sort();
}
